/* MEERA'S OWN SEARCH, FOR HER ROUTER (v2 rebuild, Phase 5, 2 Nov 2026).
 *
 *   node meera/router/build-search.cjs           → meera/router/src/search.gen.js
 *   node meera/router/build-search.cjs --check   only says whether it is what her files make (exit 1 if not)
 *
 * The router answers with the very code her browser runs — not a copy written again: her understanding of spelling
 * (meera/client/src/understand.ts) and her search (legacy/guide-tours.js, legacy/guide-ask.js), joined unchanged inside
 * one function, with small stand-ins for what the page would give (no screen, no storage, no network). So on the same
 * answers the router finds what the browser finds. The file carries a fingerprint of those sources; the router's tests
 * fail if it is out of date (they need no esbuild, so they run on GitHub as they are). */
const fs = require('fs'), path = require('path'), crypto = require('crypto');
const ROOT = path.join(__dirname, '..', '..');
const SRC = path.join(ROOT, 'meera', 'client', 'src');
const OUT = path.join(__dirname, 'src', 'search.gen.js');
/* her older files are .js until each becomes .ts (Phase 6): whichever is there */
const pick = f => (fs.existsSync(path.join(SRC, f + '.ts')) ? f + '.ts' : f + '.js');
const FILES = ['understand.ts', pick('legacy/guide-tours'), pick('legacy/guide-ask')];

function sources() { return FILES.map(f => fs.readFileSync(path.join(SRC, f), 'utf8').replace(/\r\n/g, '\n')); }
function fingerprint() { return crypto.createHash('sha256').update(sources().join('\n/*--*/\n')).digest('hex').slice(0, 16); }

function make() {
  const esbuild = require(path.join(ROOT, 'Replenish-App', 'node_modules', 'esbuild'));
  const js = (src, f) => (f.endsWith('.ts') ? esbuild.transformSync(src, { loader: 'ts', legalComments: 'inline' }).code : src);
  const [und, tours, ask] = sources().map((s, i) => js(s, FILES[i]));
  const undJs = und;
  return `/* GENERATED by meera/router/build-search.cjs from meera/client/src/${FILES.join(', ')} — do not edit.
 * Meera's own search, the code her browser runs, for her router. Sources fingerprint: ${fingerprint()} */
export const SOURCES = ${JSON.stringify(fingerprint())};
export function makeSearch() {
  /* what the page would give her: here, only what one question needs */
  const host = { screen: '', people: [], words: [], switches: new Set(), tabs: [], admin: false };
  const ERP_MEERA = { v: 2, user: () => ({ email: '', admin: host.admin, tabs: host.tabs, vendor: false }), signedIn: () => false,
    token: () => Promise.resolve(null), screen: () => host.screen, openScreen: () => false, people: () => host.people, phone: () => false,
    on() {}, switchOn: n => host.switches.has(n), words: () => host.words };
  const meeraOn = n => host.switches.has(n);
  const document = { querySelectorAll: () => [], querySelector: () => null, getElementById: () => null };
  const localStorage = { getItem: () => null, setItem() {}, removeItem() {} };
  const esc = s => String(s == null ? '' : s).replace(/[<>&"]/g, c => ({ '<': '&lt;', '>': '&gt;', '&': '&amp;', '"': '&quot;' })[c]);
  const $ = () => null;
  const fetch = () => Promise.reject(new Error('no network for the search'));
/* ---- meera/client/src/understand.ts ---- */
${undJs}
/* ---- meera/client/src/legacy/guide-tours.js ---- */
${tours}
/* ---- meera/client/src/legacy/guide-ask.js ---- */
${ask}
/* ---- what the router uses ---- */
  return {
    host,
    /** her answers (as in meera-bank.json) and her meaning table (meera-words.bin, or none) */
    load(list, words) {
      GA_BANK = gaBankIndex(list); GA_DICT = null; GA_SEM = null;
      if (words) { GA_W = gaWordsParse(words); gaSemIndex(); } else GA_W = false;
    },
    /** one question, as the browser's window.MEERA.find does it: understood (spell on), then searched */
    find(q) {
      const u = gaSpell(q);
      GA_SPELL_FIXED = u.changes.length > 0;
      try { const r = gaRead(u.text); return { understood: u, lang: r.lang, hits: gaBankFind(r.means, r.words, u.text), offTopic: gaOffTopic(r.means) }; }
      finally { GA_SPELL_FIXED = false; }
    },
  };
}
`;
}
module.exports = { fingerprint, FILES };

if (require.main === module) {
  if (process.argv.includes('--check')) {
    const now = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
    const m = /export const SOURCES = "([0-9a-f]+)"/.exec(now);
    if (!m || m[1] !== fingerprint()) { console.log('meera/router/src/search.gen.js is NOT what her files make — run node meera/router/build-search.cjs'); process.exit(1); }
    console.log('search.gen.js is what her files make (' + m[1] + ')');
  } else {
    fs.writeFileSync(OUT, make());
    console.log('built meera/router/src/search.gen.js (' + Math.round(fs.statSync(OUT).size / 1024) + ' KB, ' + fingerprint() + ')');
  }
}
